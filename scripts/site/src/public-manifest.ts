import { z } from 'zod';

import { publicObjectUrl, STORAGE_PATHS, validate, type EngineConfig } from '@hcm/shared';

import { readConfigJs } from './config-js.js';
import { SiteBuildError, issuesText } from './errors.js';
import type { SiteFileSystem } from './files.js';

/**
 * A site that reads the manifest the admin publishes (PLAN → Architecture: the public viewer GETs
 * `gs://<project>-public/cities/{city}/manifest.json`; `DECISIONS-for-review.md` §51e). A site whose `site.json` says
 * `publicManifest: true` and whose build names the public bucket (`HCM_PUBLIC_BUCKET`, a repository variable in CI) gets a
 * generated `config.js` whose `manifestUrl` is that object's https address, and no bundled snapshot: the page fetches what
 * the admin last published, never Firestore. Without a bucket the site serves the bundled seed snapshot, as before.
 *
 * The page's CSP then names the bucket's origin (the manifest and its photos) and the project's crash-report endpoint,
 * which a published manifest names (`https://<region>-<project>.cloudfunctions.net/telemetry-reportError`, built from
 * the committed `infra/project.json` the same way the functions build it).
 */

/** The committed project file: where the public bucket's project and region come from. */
const PROJECT_FILE = 'infra/project.json';

const projectSchema = z.looseObject({
    projectId: z.string().regex(/^[a-z][a-z0-9-]{4,29}$/),
    region: z.string().regex(/^[a-z]+-[a-z]+\d$/),
});

export interface PublicManifest {
    /** The served `config.js`: the site's own configuration with the bucket's manifest address. */
    readonly configSource: string;
    readonly config: EngineConfig;
    /** Origins the page's CSP adds to `connect-src` beyond the manifest's: the crash-report endpoint. */
    readonly connect: readonly string[];
}

function readProject(files: SiteFileSystem, path: string): z.infer<typeof projectSchema> {
    if (!files.isFile(path)) {
        throw new SiteBuildError(`${path} is missing: a site reading the public bucket needs the project's region and id`);
    }
    let input: unknown;
    try {
        input = JSON.parse(files.readText(path));
    } catch (error: unknown) {
        throw new SiteBuildError(`${path}: not JSON: ${String(error)}`);
    }
    const result = validate(projectSchema, input);
    if (!result.ok) {
        throw new SiteBuildError(`${path}: invalid project file\n${issuesText(result.issues)}`);
    }
    return result.value;
}

/** The https address of `cities/<cityId>/manifest.json` in `bucket`; a name that is not a bucket's fails the build. */
function publicManifestUrl(bucket: string, cityId: string): string {
    try {
        return publicObjectUrl(bucket, STORAGE_PATHS.manifest(cityId));
    } catch (error: unknown) {
        throw new SiteBuildError(`HCM_PUBLIC_BUCKET "${bucket}" with the city "${cityId}" names no public object: ${String(error)}`);
    }
}

/** `config` without its manifest source (the bundled `manifestUrl` or an inline `manifest`). */
function withoutManifest(config: EngineConfig): EngineConfig {
    return Object.fromEntries(Object.entries(config).filter(([key]) => key !== 'manifestUrl' && key !== 'manifest'));
}

/** The generated `config.js` of `config` (one literal assignment, as `readConfigJs` requires). */
function configScript(config: EngineConfig, siteDir: string): string {
    return [
        `// Generated by the site build from ${siteDir}/config.js: the manifest the admin publishes to the public bucket`,
        '// (HCM_PUBLIC_BUCKET; docs/ENGINE_API.md → config.js).',
        `window.HistoricCityMapConfig = ${JSON.stringify(config)};`,
        '',
    ].join('\n');
}

/** The served configuration and CSP additions of a site reading `bucket`; `config` is the site's committed one. */
export function publicManifest(bucket: string, config: EngineConfig, siteDir: string, files: SiteFileSystem): PublicManifest {
    const cityId = config.cityId;
    if (cityId === undefined) {
        throw new SiteBuildError(`${siteDir}/config.js names no cityId: the public bucket's manifest is cities/<cityId>/manifest.json`);
    }
    const { projectId, region } = readProject(files, PROJECT_FILE);
    const served: EngineConfig = { ...withoutManifest(config), cityId, manifestUrl: publicManifestUrl(bucket, cityId) };
    const configSource = configScript(served, siteDir);
    return {
        configSource,
        config: readConfigJs(configSource, `${siteDir}/config.js`),
        connect: [`https://${region}-${projectId}.cloudfunctions.net`],
    };
}
